-- modules/clock.lua
-- TESSERA · встроенный модуль
-- Эталонный модуль: показывает текущее время, обновляется каждую секунду.
-- Это самый простой из встроенных модулей — если пишешь свой первый
-- кастомный модуль, начни с копии этого файла.

local M = {}

-- init() вызывается один раз при загрузке модуля.
function M.init()
    M.current_time = time.format(time.now(), "HH:mm:ss")

    -- Подписываемся на системный тик (раз в секунду).
    -- Событие рассылается всем модулям одновременно — каждый решает
    -- сам, реагировать на него или нет.
    event.on("time.tick", function()
        M.current_time = time.format(time.now(), "HH:mm:ss")
    end)
end

-- ui() вызывается перед каждой перерисовкой и возвращает дерево
-- элементов интерфейса, которое Dart-рендерер превратит в виджеты.
function M.ui()
    return ui.column({
        ui.text(M.current_time)
    })
end

module = M
return M
